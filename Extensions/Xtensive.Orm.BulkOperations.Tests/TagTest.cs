using System.Collections.Generic;
using System.Linq;
using System.Threading.Tasks;
using NUnit.Framework;
using TestCommon.Model;

namespace Xtensive.Orm.BulkOperations.Tests
{
  internal class TagTest : BulkOperationBaseTest
  {
    [Test]
    public void BulkDelete()
    {
      using (var session = Domain.OpenSession())
      using (var trx = session.OpenTransaction()) {
        _ = new Bar(session) { Name = "test" };
        var allCommands = new List<string>();

        session.Events.DbCommandExecuting += SqlCapturer;
        _ = session.Query.All<Bar>().Tag("bulkDeleteTag").Where(a => a.Name == "test").Delete();
        session.Events.DbCommandExecuting -= SqlCapturer;

        Assert.That(allCommands, Has.Some.Contains("/*bulkDeleteTag*/"));
        trx.Complete();

        void SqlCapturer(object sender, DbCommandEventArgs args) => allCommands.Add(args.Command.CommandText);
      }
    }

    [Test]
    public async Task BulkDeleteAsync()
