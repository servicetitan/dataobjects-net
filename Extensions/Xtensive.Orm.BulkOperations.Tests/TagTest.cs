    [Test]
    public void BulkUpdateWithLimitationCarriesTag()
    {
      // SQL Server's UPDATE TOP(N)/DELETE TOP(N) path is generated by a driver-specific
      // compiler override that bypasses the shared base-compiler comment emission,
      // so it needs its own regression coverage.
      CheckLimitationSupported();

      using (var session = Domain.OpenSession())
      using (var trx = session.OpenTransaction()) {
        _ = new Bar(session) { Name = "test", Count = 3 };
        _ = new Bar(session) { Name = "test", Count = 3 };
        var allCommands = new List<string>();

        session.Events.DbCommandExecuting += SqlCapturer;
        _ = session.Query.All<Bar>().Tag("bulkUpdateLimitTag").Where(a => a.Name == "test").Take(1)
          .Set(a => a.Count, 5).Update();
        session.Events.DbCommandExecuting -= SqlCapturer;

        Assert.That(allCommands, Has.Some.Contains("/*bulkUpdateLimitTag*/"));
        trx.Complete();

        void SqlCapturer(object sender, DbCommandEventArgs args) => allCommands.Add(args.Command.CommandText);
      }
    }

    [Test]
    public void BulkDeleteWithLimitationCarriesTag()
    {
      CheckLimitationSupported();

      using (var session = Domain.OpenSession())
      using (var trx = session.OpenTransaction()) {
        _ = new Bar(session) { Name = "test" };
        _ = new Bar(session) { Name = "test" };
        var allCommands = new List<string>();

        session.Events.DbCommandExecuting += SqlCapturer;
        _ = session.Query.All<Bar>().Tag("bulkDeleteLimitTag").Where(a => a.Name == "test").Take(1).Delete();
        session.Events.DbCommandExecuting -= SqlCapturer;

        Assert.That(allCommands, Has.Some.Contains("/*bulkDeleteLimitTag*/"));
        trx.Complete();

        void SqlCapturer(object sender, DbCommandEventArgs args) => allCommands.Add(args.Command.CommandText);
      }
    }

    private void CheckLimitationSupported()
    {
      if (!Domain.StorageProviderInfo.Supports(Providers.ProviderFeatures.UpdateLimit)) {
        throw new IgnoreException("Test is inconclusive for current provider");
      }
    }
  }
}
